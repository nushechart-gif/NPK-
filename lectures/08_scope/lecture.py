# ============ СЕКЦИЯ 1. Глобальные переменные ============
# Создаются ВНЕ функции. Видны во всей программе.

hero_name = "Артур"
gold = 100

print("Герой:", hero_name)
print("Золото:", gold)


# ============ СЕКЦИЯ 2. Локальные переменные ============
# Создаются ВНУТРИ функции. Видны ТОЛЬКО внутри этой функции.
# После завершения функции они исчезают.

def show_info():
    message = "Привет из функции!"
    print(message)

show_info()
# print(message)  # ОШИБКА! Переменная message не существует снаружи функции


# ============ СЕКЦИЯ 3. Функция может ЧИТАТЬ глобальные переменные ============

score = 50

def show_score():
    print("Счёт:", score)   # Читаем глобальную переменную — можно!

show_score()


# ============ СЕКЦИЯ 4. ТИХАЯ ОШИБКА: функция НЕ меняет глобальную переменную ============
# Это САМЫЙ коварный момент! Если внутри функции создать переменную с тем же именем,
# что и глобальная, то функция создаст СВОЮ локальную копию. Глобальная не изменится!

health = 100

def take_damage():
    health = 70   # Создали ЛОКАЛЬНУЮ переменную health, глобальная осталась 100
    print("Внутри функции:", health)

take_damage()
print("Снаружи функции:", health)   # Всё ещё 100! Глобальная не изменилась!


# ============ СЕКЦИЯ 5. ПРАВИЛЬНЫЙ СПОСОБ: параметры и return ============
# Чтобы изменить значение, нужно передать его параметром и вернуть через return.

health = 100

def apply_damage(hp, damage):
    print("Получен урон:", damage)
    return hp - damage   # Возвращаем НОВОЕ значение

health = apply_damage(health, 30)   # Сохраняем результат обратно в health
print("Здоровье после удара:", health)   # 70


# ============ СЕКЦИЯ 6. Ещё один пример: накопитель ============

money = 50

def add_coins(current_money, amount):
    return current_money + amount

money = add_coins(money, 20)
print("Монет:", money)   # 70

money = add_coins(money, 10)
print("Монет:", money)   # 80


# ============ СЕКЦИЯ 7. Параметр — это тоже локальная переменная ============

x = 5

def change(value):
    value = value + 10   # value — локальная, меняется только внутри
    print("Внутри функции:", value)

change(x)
print("Снаружи функции:", x)   # Всё ещё 5!
