# ============ СЕКЦИЯ 2. Ловушка для ошибок (try / except) ============
# try (попробуй) — выполняй этот код.
# except (кроме) — если произошла ошибка, не падай, а сделай вот это.

print("Сколько у тебя золота?")
try:
    gold = int(input())
    print("Отлично, у тебя", gold, "монет!")
except ValueError:
    print("Эй! Нужно было ввести число, а не буквы. Я обнуляю твоё золото.")
    gold = 0

print("Игра продолжается!")


# ============ СЕКЦИЯ 3. Цикл, пока не введут правильно ============
# Идеальный паттерн для меню квеста. 
# Мы не пускаем игрока дальше, пока он не введёт корректные данные.

while True:
    try:
        age = int(input("Сколько лет твоему герою? "))
        break   # Если дошли сюда — ошибки не было, выходим из цикла
    except ValueError:
        print("Ошибка! Введите число цифрами.")

print("Герою", age, "лет. Начинаем приключение!")


# ============ СЕКЦИЯ 4. Разные типы ошибок ============
# Можно ловить конкретные ошибки и реагировать на них по-разному.

try:
    health = 100
    hits = int(input("Сколько ударов ты нанес? "))
    damage_per_hit = 10
    
    # Здесь может быть деление на ноль, если ввести 0
    average = health / hits  
    print("Средний урон:", average)

except ValueError:
    print("Ты ввёл не число!")
except ZeroDivisionError:
    print("На ноль делить нельзя! Ты что, не бил вообще?")


# ============ СЕКЦИЯ 5. Ошибки в словарях (KeyError) ============
# Если мы пытаемся достать из словаря ключ, которого там нет.

hero = {"name": "Артур", "health": 100}

try:
    print("Магия:", hero["magic"])
except KeyError:
    print("У героя нет такого параметра! Добавь его сначала.")


