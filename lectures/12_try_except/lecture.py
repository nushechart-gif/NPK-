# ============ СЕКЦИЯ 7. Применение в квесте: безопасное меню ============
# Делаем так, чтобы меню не вылетало при неверном вводе.

def safe_menu():
    while True:
        print("\n1 - Атаковать")
        print("2 - Бежать")
        choice = input("Выбор: ")
        
        if choice in ["1", "2"]:
            return choice
        else:
            print("Неверная команда. Попробуй ещё раз.")

print("Ты встретил дракона!")
action = safe_menu()
print("Ты выбрал действие номер", action)
