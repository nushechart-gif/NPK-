# ============ СЕКЦИЯ 1. Что такое переменная? ============
# Переменная — это коробка с именем, в которой лежат данные.

hero_name = "Артур"
health = 100

print("Герой:", hero_name)
print("Здоровье:", health)


# ============ СЕКЦИЯ 2. Изменение переменной ============
# В коробку можно положить новое значение. Старое при этом стирается.

health = 80
print("После удара здоровье:", health)

health = health - 30  # Берём старое значение, вычитаем 30, кладём обратно
print("После второго удара:", health)


# ============ СЕКЦИЯ 3. Основные типы данных ============

# 1. int (integer) — целые числа
gold = 50

# 2. float — дробные числа (всегда через точку, не через запятую!)
weight = 75.5

# 3. str (string) — строки, текст. Всегда в кавычках (одинарных или двойных)
weapon = "меч"
phrase = 'Я иду на север'

# 4. bool (boolean) — логический тип. Только два значения: True (истина) или False (ложь)
has_key = False
is_alive = True


# ============ СЕКЦИЯ 4. Как узнать тип данных? ============
# Функция type() показывает, что лежит в переменной.

print(type(gold))    # <class 'int'>
print(type(weight))  # <class 'float'>
print(type(weapon))  # <class 'str'>
print(type(has_key)) # <class 'bool'>
