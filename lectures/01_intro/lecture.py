# ============ СЕКЦИЯ 1. Вывод на экран (print) ============
# print() — это команда, которая показывает текст или числа на экране.

print("Привет, мир!")
print("Мы начинаем изучать Python.")

# Можно выводить несколько кусков через запятую — Питон сам поставит пробел
print("Python", "это", "круто")


# ============ СЕКЦИЯ 2. Ввод данных (input) ============
# input() — программа останавливается и ждёт, пока пользователь что-то напечатает и нажмёт Enter.

name = input("Как тебя зовут? ")
print("Привет,", name, "!")

# Важно: input() ВСЕГДА возвращает текст (строку), даже если ввели цифры!
age = input("Сколько тебе лет? ")
print("Тебе", age, "лет.")


# ============ СЕКЦИЯ 3. Комментарии ============
# Решётка # в начале строки означает комментарий.
# Питон игнорирует всё, что после неё. Это заметки для людей.

# print("Эта строка не выполнится, потому что она закомментирована")
print("А эта выполнится") # Комментарий можно писать и в конце строки
