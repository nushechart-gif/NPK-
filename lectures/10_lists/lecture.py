# ============================================================
# ЛЕКЦИЯ 10. Списки: инвентарь героя
# ============================================================

# ============ СЕКЦИЯ 1. Что такое список ============
# Список — это переменная, которая хранит сразу МНОГО значений.
# Создаётся в квадратных скобках [ ].

inventory = []                       # пустой рюкзак
inventory = ["меч"]                  # рюкзак с одним предметом
inventory = ["меч", "зелье", "ключ"] # три предмета

print(inventory)


# ============ СЕКЦИЯ 2. Индексы — достаём предмет ============
# Нумерация с нуля, как в строках.

print(inventory[0])    # меч — первый
print(inventory[1])    # зелье — второй
print(inventory[-1])   # ключ — последний


# ============ СЕКЦИЯ 3. Добавление предмета — .append() ============
# Кладём предмет в конец рюкзака.

inventory = []
inventory.append("меч")
print(inventory)        # ['меч']

inventory.append("зелье")
print(inventory)        # ['меч', 'зелье']


# ============ СЕКЦИЯ 4. Размер списка — len() ============

print(len(inventory))   # сколько предметов в рюкзаке


# ============ СЕКЦИЯ 5. Проверка наличия — оператор in ============
# Читается как обычный английский: "если ключ в инвентаре"

if "ключ" in inventory:
    print("Дверь открыта!")
else:
    print("Нужен ключ.")


# ============ СЕКЦИЯ 6. Удаление предмета — .remove() ============
# Герой использовал зелье — оно исчезло.

inventory.remove("зелье")
print(inventory)


# ============ СЕКЦИЯ 7. Перебор списка через for ============
# Показываем игроку всё, что у него в рюкзаке.

inventory = ["меч", "зелье", "ключ"]

print("Твой инвентарь:")
for item in inventory:
    print("-", item)


# ============ СЕКЦИЯ 8. Применение в квесте ============

inventory = []

choice = input("подобрать / инвентарь: ").lower().strip()

if choice == "подобрать":
    found = "факел"
    inventory.append(found)
    print("Ты подобрал:", found)

elif choice == "инвентарь":
    if len(inventory) == 0:
        print("Рюкзак пуст.")
    else:
        print("В твоём рюкзаке:")
        for item in inventory:
            print("-", item)


# ============ СЕКЦИЯ 9. Защита от ошибок ============
# Нельзя удалить то, чего нет — будет ошибка. Сначала проверяем!

if "дракон" in inventory:
    inventory.remove("дракон")
else:
    print("Такого предмета нет в рюкзаке.")
