# ============ СЕКЦИЯ 1. Что такое reversed() ============
# reversed() — это встроенная функция, которая переворачивает последовательность.
# В отличие от среза [::-1], она НЕ создаёт новую копию, а просто идёт с конца.
# Это экономит память, особенно для больших списков.


# ============ СЕКЦИЯ 2. reversed() со списком ============

inventory = ["меч", "зелье", "ключ", "факел"]

# Перебираем список в обратном порядке
print("Инвентарь в обратном порядке:")
for item in reversed(inventory):
    print("-", item)
# - факел
# - ключ
# - зелье
# - меч


# ============ СЕКЦИЯ 3. Сравнение: [::-1] vs reversed() ============

numbers = [1, 2, 3, 4, 5]

# Способ 1: Срез [::-1] создаёт НОВЫЙ список
reversed_list = numbers[::-1]
print("Срез:", reversed_list)   # [5, 4, 3, 2, 1]
# Минус: занимает дополнительную память

# Способ 2: reversed() НЕ создаёт новый список, а идёт с конца
for num in reversed(numbers):
    print(num, end=" ")   # 5 4 3 2 1
print()
# Плюс: экономит память, работает быстрее


# ============ СЕКЦИЯ 4. reversed() со строкой ============
# reversed() работает и со строками, но возвращает итератор символов.

word = "привет"

# Перебираем символы в обратном порядке
print("Слово задом наперёд:")
for char in reversed(word):
    print(char, end="")   # тевирп
print()

# Если нужно получить строку (не просто напечатать), используем .join()
reversed_word = "".join(reversed(word))
print("Перевёрнутое слово:", reversed_word)   # тевирп


# ============ СЕКЦИЯ 5. Применение в квесте: обратный отсчёт ============
# Классика — обратный отсчёт перед боем.

print("Битва начнётся через:")
for i in reversed(range(1, 6)):   # 5, 4, 3, 2, 1
    print(i)
print("В бой!")


# ============ СЕКЦИЯ 6. Применение в квесте: история ходов ============
# Показываем последние действия игрока в обратном порядке.

history = ["вошёл в лес", "нашёл монеты", "встретил волка", "убежал"]

print("Последние действия (от новых к старым):")
for action in reversed(history):
    print("-", action)


# ============ СЕКЦИЯ 7. Задача про переворот слов (альтернатива срезу) ============
# Та самая задача из практики, но через reversed() вместо [::-1].

phrase = "Hello World from Python"
words = phrase.split()                    # ['Hello', 'World', 'from', 'Python']
reversed_words = list(reversed(words))    # ['Python', 'from', 'World', 'Hello']
result = " ".join(reversed_words)
print(result)                             # Python from World Hello

# Или в одну строку:
result = " ".join(reversed(phrase.split()))
print(result)


# ============ СЕКЦИЯ 8. Частые ошибки ============

# ❌ Ошибка 1: Пытаться обратиться по индексу к reversed()
numbers = [1, 2, 3, 4, 5]
rev = reversed(numbers)
# print(rev[0])   # ❌ ОШИБКА! reversed() возвращает итератор, не список

# ✅ Правильно: сначала преобразовать в список
rev_list = list(reversed(numbers))
print(rev_list[0])   # 5

# Или использовать в цикле for
for num in reversed(numbers):
    print(num)


# ❌ Ошибка 2: Забыть, что reversed() не меняет исходный список
inventory = ["меч", "зелье"]
reversed(inventory)   # Это не меняет inventory!
print(inventory)      # ['меч', 'зелье'] — всё ещё в исходном порядке

# ✅ Правильно: сохранить результат
inventory_reversed = list(reversed(inventory))
print(inventory_reversed)   # ['зелье', 'меч']


