# ============ СЕКЦИЯ 1. Простейший цикл for ============
# Цикл for используется, когда мы ЗАРАНЕЕ знаем, сколько раз нужно повторить действие.
# Переменная i (можно назвать как угодно) принимает значения по очереди.

for i in range(5):
    print("Шаг номер:", i)
# Важно: range(5) выдает числа 0, 1, 2, 3, 4. Пятерка НЕ включается!


# ============ СЕКЦИЯ 2. Функция range(старт, стоп) ============
# Можно задать, с какого числа начать и на каком закончить (не включая его).

print("\nОбратный отсчет перед боем:")
for i in range(3, 0, -1):
    print(i)
print("В бой!")


# ============ СЕКЦИЯ 3. Цикл for со строками (предвкушение списков) ============
# Цикл for умеет перебирать не только числа, но и буквы в слове.
# Это очень пригодится нам позже.

word = "МЕЧ"
print("\nЗачарование меча:")
for letter in word:
    print("Руна:", letter)


# ============ СЕКЦИЯ 4. Накопитель в цикле for ============
# Считаем общий урон от серии ударов.

total_damage = 0
hits = 5
damage_per_hit = 10

for i in range(hits):
    total_damage = total_damage + damage_per_hit
    print(f"Удар {i + 1}! Нанесено урона: {damage_per_hit}")

print("Общий урон за серию:", total_damage)
