# ============ СЕКЦИЯ 1. Простое условие if ============
# Если условие в скобках True (истина), код внутри выполняется.
# Обязательно ставим двоеточие и делаем отступ (Tab)!

health = 50

if health > 0:
    print("Герой жив и может идти дальше.")


# ============ СЕКЦИЯ 2. Ветвление if / else ============
# Если условие не выполнилось, срабатывает блок else (иначе).

gold = 10
sword_price = 50

if gold >= sword_price:
    print("Ты купил меч!")
else:
    print("Не хватает золота. Иди фармить.")


# ============ СЕКЦИЯ 3. Множественный выбор if / elif / else ============
# Основа любого текстового квеста — меню выбора.
# elif (else if) позволяет проверить много вариантов подряд.

print("\n1 - Атаковать")
print("2 - Убежать")
print("3 - Отдохнуть")

choice = input("Твой выбор: ")

if choice == "1":
    print("Ты наносишь удар мечом!")
elif choice == "2":
    print("Ты сбежал с поля боя.")
elif choice == "3":
    print("Ты сел у костра и восстановил силы.")
else:
    # Срабатывает, если ввели что-то кроме 1, 2 или 3
    print("Я не понял такую команду.")


# ============ СЕКЦИЯ 4. Логические операторы and, or ============
# and — И (оба условия должны быть True)
# or — ИЛИ (хотя бы одно условие True)

has_key = True
has_magic = False

if has_key and has_magic:
    print("Ты открыл магическую дверь ключом.")
elif has_key or has_magic:
    print("Ты прошел через дверь (ключом или магией).")
else:
    print("Дверь заперта, и магии нет.")
