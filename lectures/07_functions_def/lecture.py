# ============ СЕКЦИЯ 1. Самая простая функция ============
# def создаёт функцию. Дальше идёт имя, скобки и двоеточие.
# Всё, что с отступом — это тело функции (что она делает).

def hello():
    print("Привет!")

# Функция создана, но НЕ запущена. Чтобы запустить — вызываем:
hello()
hello()
hello()


# ============ СЕКЦИЯ 2. Функция с параметром ============
# Параметр — это "вход" в функцию. Место, куда попадут данные при вызове.

def greet(name):
    print("Привет,", name, "!")

greet("Аня")
greet("Петя")
greet("Студент")


# ============ СЕКЦИЯ 3. Функция с несколькими параметрами ============

def add(a, b):
    result = a + b
    print("Сумма:", result)

add(3, 5)
add(10, 20)


# ============ СЕКЦИЯ 4. Возвращаемое значение (return) ============
# return ОТДАЁТ значение обратно в программу.
# Его можно сохранить в переменную и использовать дальше.

def multiply(a, b):
    return a * b

result = multiply(3, 5)
print("Результат:", result)   # 15

# А вот так результат теряется:
multiply(10, 20)   # функция вернула 200, но мы не сохранили


# ============ СЕКЦИЯ 5. Разница между print и return ============
# print — показывает на экране, но НЕ отдаёт значение программе.
# return — отдаёт значение программе, но НЕ показывает на экране.

def show(x):
    print(x)          # показывает, но возвращает None

def give(x):
    return x          # возвращает, но не показывает

a = show(10)
print("a =", a)       # a = None (функция ничего не вернула)

b = give(10)
print("b =", b)       # b = 10 (функция вернула значение)


# ============ СЕКЦИЯ 6. Функции в квесте ============
# Вот как мы используем функции в нашем текстовом квесте.

def apply_damage(health, damage):
    print("Ты получаешь урон", damage, "!")
    return health - damage

def heal(health, amount):
    print("Ты восстанавливаешь", amount, "здоровья.")
    return health + amount

health = 100
print("Начальное здоровье:", health)

health = apply_damage(health, 30)
print("После удара:", health)

health = heal(health, 20)
print("После лечения:", health)
