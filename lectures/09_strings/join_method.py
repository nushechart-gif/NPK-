# ============================================================
# ЛЕКЦИЯ: Метод .join() — склейка списка в строку
# ============================================================

# ============ СЕКЦИЯ 1. Что такое .join() ============
# .join() — это обратная операция к .split().
# .split() разбивает строку на список слов.
# .join() склеивает список обратно в строку.
#
# Формат: "разделитель".join(список)
# Разделитель — это то, что будет стоять между словами.


# ============ СЕКЦИЯ 2. Простые примеры ============

words = ["меч", "зелье", "ключ"]

# Склеиваем через пробел
print(" ".join(words))          # меч зелье ключ

# Склеиваем через запятую с пробелом
print(", ".join(words))         # меч, зелье, ключ

# Склеиваем через тире
print(" - ".join(words))        # меч - зелье - ключ

# Склеиваем вообще без разделителя
print("".join(words))           # мечзельеключ


# ============ СЕКЦИЯ 3. Разбить и склеить обратно ============
# .split() и .join() часто работают в паре.
# Разбили строку на слова, что-то с ними сделали, склеили обратно.

phrase = "Hello World from Python"

# Разбиваем на список слов
words = phrase.split()                  # ['Hello', 'World', 'from', 'Python']

# Переворачиваем список (это та самая задача из практики!)
words = words[::-1]                     # ['Python', 'from', 'World', 'Hello']

# Склеиваем обратно через пробел
result = " ".join(words)                # Python from World Hello

print(result)


# ============ СЕКЦИЯ 4. Применение в квесте ============

# Показать инвентарь красиво, в одну строку
inventory = ["меч", "зелье", "факел"]
print("В твоём рюкзаке: " + ", ".join(inventory))
# В твоём рюкзаке: меч, зелье, факел


# Собрать команды из списка действий
actions = ["атаковать", "бежать", "лечиться"]
print("Доступные команды: " + " | ".join(actions))
# Доступные команды: атаковать | бежать | лечиться


# ============ СЕКЦИЯ 5. Частые ошибки ============

# ❌ Ошибка 1: Вызвать .join() у списка, а не у строки
words = ["меч", "зелье"]
# print(words.join(" "))   # ❌ ОШИБКА! У списка нет метода .join()

# ✅ Правильно: вызывать у строки-разделителя
print(" ".join(words))


# ❌ Ошибка 2: Передать в .join() не список, а строку
# print(" ".join("привет"))   # Склеит буквы: п р и в е т

# ✅ Правильно: передать список
print(" ".join(["привет"]))   # привет


