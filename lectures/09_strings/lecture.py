# ============ СЕКЦИЯ 1. Строка — это последовательность символов ============
# К каждому символу можно обратиться по номеру (индексу).
# Нумерация начинается С НУЛЯ!

word = "подземелье"

print(word[0])     # п — первый символ
print(word[1])     # о — второй символ
print(word[-1])    # е — последний символ (отрицательный индекс идёт с конца)
print(word[-2])    # ь — предпоследний


# ============ СЕКЦИЯ 2. Срезы — берём кусок строки ============
# Формат: строка[начало:конец]
# ВАЖНО: конец НЕ включается (как в range)!

print(word[0:3])    # под — символы 0, 1, 2
print(word[3:6])    # зем — символы 3, 4, 5
print(word[4:])     # емелье — с 4-го до конца
print(word[:3])     # под — с начала до 3-го (не включая)


# ============ СЕКЦИЯ 3. Длина строки — len() ============

print(len(word))    # 10 — сколько символов в строке


# ============ СЕКЦИЯ 4. Основные методы строк ============

text = "  Ты ЗАШЁЛ в тёмный ЛЕС  "

# .lower() — все буквы в нижний регистр
print(text.lower())

# .upper() — все буквы в верхний регистр
print(text.upper())

# .strip() — убирает пробелы в начале и в конце
print(text.strip())

# .replace(старое, новое) — заменяет одно на другое
print(text.replace("тёмный", "светлый"))

# .split() — разбивает строку на список по пробелам
command = "взять меч"
parts = command.split()
print(parts)        # ['взять', 'меч']
print(parts[0])     # взять
print(parts[1])     # меч

# .find(подстрока) — ищет и возвращает индекс начала, или -1 если нет
print(text.find("лес"))     # найдёт позицию
print(text.find("дракон"))  # -1 — такого нет

# .count(подстрока) — сколько раз встречается
text2 = "гоблин гоблин дракон гоблин"
print(text2.count("гоблин"))   # 3


# ============ СЕКЦИЯ 5. Применение в квесте: парсер команд ============
# Теперь игрок может писать команды словами, а не цифрами!

command = input("Что делаешь? ").lower().strip()
parts = command.split()
action = parts[0]

if action == "взять":
    print("Ты берёшь предмет.")
elif action == "идти":
    print("Ты идёшь.")
elif action == "осмотреть":
    print("Ты осматриваешься.")
else:
    print("Я не понял.")


# ============ СЕКЦИЯ 6. Загадка с паролем через срез ============

password = "сокровище"
answer = input("Введи начало пароля (первые 3 буквы): ").lower().strip()

if answer == password[0:3]:
    print("Дверь открылась!")
else:
    print("Неверно. Дверь осталась закрытой.")
