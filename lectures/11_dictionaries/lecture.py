# ============================================================

# ============ СЕКЦИЯ 1. Что такое словарь ============
# Словарь хранит данные парами: КЛЮЧ — ЗНАЧЕНИЕ.
# Создаётся в фигурных скобках { }.
# Ключ — это "имя", по которому мы достаём значение.

hero = {
    "name": "Артур",
    "health": 100,
    "gold": 50,
    "weapon": "меч"
}

print(hero)


# ============ СЕКЦИЯ 2. Доступ по ключу ============
# Обращаемся не по номеру (как в списке), а по имени ключа.

print(hero["name"])      # Артур
print(hero["health"])    # 100
print(hero["gold"])      # 50


# ============ СЕКЦИЯ 3. Изменение значения ============

hero["health"] = 80
print("После удара здоровье:", hero["health"])

hero["gold"] = hero["gold"] + 20
print("Нашёл монеты, теперь золота:", hero["gold"])


# ============ СЕКЦИЯ 4. Добавление новой пары ============

hero["armor"] = "кольчуга"
print(hero)


# ============ СЕКЦИЯ 5. Проверка наличия ключа — in ============

if "weapon" in hero:
    print("У героя есть оружие:", hero["weapon"])
else:
    print("Оружия нет.")


# ============ СЕКЦИЯ 6. Удаление пары — del ============

del hero["armor"]
print(hero)


# ============ СЕКЦИЯ 7. Перебор словаря через for ============

print("\nХарактеристики героя:")
for key in hero:
    print(key, ":", hero[key])

# Или более красивый способ через .items():
print("\nЧерез items():")
for key, value in hero.items():
    print(key, "→", value)


# ============ СЕКЦИЯ 8. Безопасный доступ — .get() ============
# Если ключа нет, .get() вернёт значение по умолчанию, а не ошибку.

print(hero.get("magic", "магии нет"))   # вернёт "магии нет"


# ============ СЕКЦИЯ 9. Применение в квесте: характеристики героя ============

hero = {
    "name": "Артур",
    "health": 100,
    "gold": 50
}

def show_hero(hero):
    print("\n---", hero["name"], "---")
    print("Здоровье:", hero["health"])
    print("Золото:", hero["gold"])

def apply_damage(hero, damage):
    hero["health"] = hero["health"] - damage
    print("Получен урон:", damage)

show_hero(hero)
apply_damage(hero, 30)
show_hero(hero)
