# ============ СЕКЦИЯ 1. Метод .setdefault() ============
# .setdefault(ключ, значение) — добавляет пару, если ключа НЕТ.
# Если ключ уже есть — ничего не меняет.
# Идеально для инвентаря: подобрать предмет, которого ещё нет.

inventory = {"меч": 1, "ключ": 2}

# Добавляем зелье (его ещё нет)
inventory.setdefault("зелье", 3)
print(inventory)   # {'меч': 1, 'ключ': 2, 'зелье': 3}

# Пытаемся добавить меч снова (он уже есть) — ничего не изменится
inventory.setdefault("меч", 5)
print(inventory)   # {'меч': 1, 'ключ': 2, 'зелье': 3} — меч остался 1


# ============ СЕКЦИЯ 2. Метод .pop() ============
# .pop(ключ) — удаляет пару и ВОЗВРАЩАЕТ значение.
# В отличие от del, мы узнаём, сколько было удалено.
# Идеально для квеста: выпил зелье — оно исчезло.

inventory = {"меч": 1, "зелье": 3, "ключ": 2}

# Забираем меч
sword_count = inventory.pop("меч")
print(f"Ты забрал меч. Его было: {sword_count}")   # Его было: 1
print(inventory)   # {'зелье': 3, 'ключ': 2}

# Выпиваем зелье
healing = inventory.pop("зелье")
print(f"Ты выпил зелье. Восстановил: {healing} здоровья")
print(inventory)   # {'ключ': 2}


# ============ СЕКЦИЯ 3. Метод .values() ============
# .values() — возвращает все ЗНАЧЕНИЯ словаря.
# Идеально для подсчёта общего количества предметов.

inventory = {"меч": 1, "зелье": 3, "ключ": 2}

# Выводим только количества
print("Количества предметов:")
for amount in inventory.values():
    print(amount)   # 1, 3, 2

# Считаем общее число предметов
total = sum(inventory.values())
print(f"Всего предметов в рюкзаке: {total}")   # 6


# ============ СЕКЦИЯ 4. Метод .keys() ============
# .keys() — возвращает все КЛЮЧИ словаря.
# Работает так же, как перебор по словарю напрямую.

inventory = {"меч": 1, "зелье": 3, "ключ": 2}

print("Названия предметов:")
for item in inventory.keys():
    print("-", item)


