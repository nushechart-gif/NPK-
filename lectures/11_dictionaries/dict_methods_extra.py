# ============ СЕКЦИЯ 6. Применение в квесте ============
# Подбор предмета, использование предмета, проверка инвентаря.

inventory = {}

# Подбираем предметы (если их ещё нет — создаём с количеством 1)
items_found = ["меч", "зелье", "зелье", "ключ", "зелье"]

for item in items_found:
    inventory.setdefault(item, 0)      # создаём ключ, если его нет
    inventory[item] = inventory[item] + 1   # увеличиваем количество

print("Ты нашёл предметы!")
print("Инвентарь:", inventory)
# Инвентарь: {'меч': 1, 'зелье': 3, 'ключ': 1}

# Используем зелье
if "зелье" in inventory:
    inventory["зелье"] = inventory["зелье"] - 1
    print("Ты выпил зелье. Осталось:", inventory["зелье"])
    
    # Если зелий не осталось — удаляем ключ
    if inventory["зелье"] == 0:
        inventory.pop("зелье")
        print("Зелья закончились.")

print("Финальный инвентарь:", inventory)
