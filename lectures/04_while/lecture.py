# ============ СЕКЦИЯ 1. Простой счетчик ============
# Цикл крутится, ПОКА условие истинно.
# Важно: переменная должна меняться внутри цикла, иначе он будет вечным!

count = 5

while count > 0:
    print("Обратный отсчет:", count)
    count = count - 1   # Уменьшаем на 1 каждый шаг

print("Поехали!")


# ============ СЕКЦИЯ 2. Цикл, который ждет пользователя ============
# Классика для игр: крутимся, пока игрок не введет правильное слово.

password = ""

while password != "секрет":
    password = input("Введи пароль: ")
    
print("Доступ разрешен!")


