# ============ СЕКЦИЯ 4. Накопитель (сумма) ============
# Считаем, сколько монет собрал герой, пока он не введет 0.
# int() превращает текст из input() в целое число.

total_gold = 0
print("Вводи найденные монеты. Чтобы закончить, введи 0.")

coin = int(input("Сколько монет нашел? "))

while coin != 0:
    total_gold = total_gold + coin
    print("Всего монет:", total_gold)
    coin = int(input("Сколько еще? "))

print("Итог в кошельке:", total_gold)
