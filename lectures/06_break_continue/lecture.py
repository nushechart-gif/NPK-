# ============ СЕКЦИЯ 1. Оператор break (прервать) ============
# break немедленно ВЫБРАСЫВАЕТ нас из цикла, даже если условие еще истинно.
# Идеально для кнопки "Выход" или "Победа" в квесте.

print("Ты идешь по лабиринту...")
for step in range(1, 100):
    print(f"Шаг {step}...")
    
    if step == 3:
        print("Ты нашел выход! Игра окончена.")
        break  # Цикл прерывается, шаги 4, 5... не выполнятся


# ============ СЕКЦИЯ 2. Оператор continue (пропустить шаг) ============
# continue прерывает ТЕКУЩИЙ шаг цикла и перекидывает нас на СЛЕДУЮЩИЙ.
# Идеально для обработки неверного ввода или пропуска врагов.

print("\nСтрельба по мишеням:")
for target in range(1, 6):
    if target == 3:
        print(f"Мишень {target} - это свой! Пропускаем.")
        continue  # Пропускаем код ниже для этой мишени
    
    print(f"Стреляем в мишень {target}! Попал!")


# ============ СЕКЦИЯ 3. break и continue в бесконечном цикле (while True) ============
# Это основа любого текстового квеста. Цикл крутится вечно, 
# пока игрок сам не решит выйти (break).

print("\n--- Меню таверны ---")
while True:
    print("\n1 - Купить зелье")
    print("2 - Послушать слухи")
    print("3 - Уйти")
    
    choice = input("Твой выбор: ")
    
    if choice == "1":
        print("Ты выпил зелье и восстановил здоровье.")
    elif choice == "2":
        print("Трактирщик рассказал о драконе в горах.")
    elif choice == "3":
        print("Ты вышел из таверны.")
        break  # Выходим из бесконечного цикла
    else:
        print("Трактирщик не понял тебя. Попробуй еще раз.")
        continue  # Возвращаемся к началу меню, не выполняя код ниже
        
    print("Ты сидишь и отдыхаешь...") # Эта строка не выполнится, если сработал break или continue
