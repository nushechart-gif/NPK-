# Стартовые характеристики героя
health = 100
gold = 10
name = input("Как зовут героя? ")

print("\nПривет,", name, "! Ты просыпаешься на опушке тёмного леса.")
print("Здоровье:", health, "| Золото:", gold)

print("\nЧто будешь делать?")
print("1 - Идти в лес")
print("2 - Пойти в деревню")
print("3 - Вернуться домой")

choice = input("Твой выбор: ")

if choice == "1":
    print("\nТы зашёл в лес и встретил волка!")
    print("Волк кусает тебя. Здоровье -30")
    health = health - 30
    print("Здоровье:", health)
    
    if health > 0:
        print("Ты выжил и нашёл кошель с золотом! +20 монет")
        gold = gold + 20
        print("Золото:", gold)
    else:
        print("Ты погиб...")

elif choice == "2":
    print("\nТы пришёл в деревню и купил зелье за 5 монет.")
    gold = gold - 5
    health = health + 20
    print("Здоровье:", health, "| Золото:", gold)

elif choice == "3":
    print("\nТы вернулся домой. Приключение окончено.")

else:
    print("\nЯ не понял тебя.")

print("\n=== ИГРА ЗАВЕРШЕНА ===")
