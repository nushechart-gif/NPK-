# Темы: циклы, счётчики, break
# Собирается после лекций 4-6
# ============================================================

health = 100
gold = 0
turns = 0

print("Ты просыпаешься в заброшенном подземелье.")
print("Выберись, пока здоровье не кончилось!\n")

while health > 0:
    turns = turns + 1
    print("--- Ход", turns, "---")
    print("Здоровье:", health, "| Золото:", gold)
    print("\n1 - Идти вперёд")
    print("2 - Отдохнуть")
    print("3 - Обыскать комнату")
    print("4 - Найти выход")
    
    choice = input("Твой выбор: ")
    
    if choice == "1":
        print("Ты идёшь вперёд и получаешь урон от ловушки (-15)")
        health = health - 15
    
    elif choice == "2":
        print("Ты отдыхаешь и восстанавливаешь силы (+10)")
        health = health + 10
    
    elif choice == "3":
        print("Ты обыскал комнату и нашёл монеты (+20)")
        gold = gold + 20
    
    elif choice == "4":
        print("Ты нашёл выход! Победа!")
        break
    
    else:
        print("Я не понял тебя.")

if health <= 0:
    print("\nТы погиб. Ходов сделано:", turns)
else:
    print("\nТы выбрался! Золота собрано:", gold, "| Ходов:", turns)

print("=== ИГРА ЗАВЕРШЕНА ===")
