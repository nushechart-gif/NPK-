def show_status(doors_opened):
    print("\n" + "="*50)
    print(f"Открыто дверей: {doors_opened} из 5")
    print("="*50)


def door_1():
    """ЗАДАЧА 1: Достань нужный предмет по индексу"""
    print("\n🚪 ДВЕРЬ 1. ИНДЕКСЫ")
    print("Страж говорит: 'Перед тобой сундук с предметами.'")
    
    chest = ["меч", "зелье", "ключ", "факел", "карта"]
    print("В сундуке:", chest)
    print("\nЗагадка: 'Чтобы пройти, возьми ТРЕТИЙ предмет из сундука.'")
    
    answer = input("Какой предмет ты берёшь? ").lower().strip()
    
    # Правильный ответ: ключ (индекс 2)
    if answer == "ключ":
        print("✅ Верно! Дверь открывается.")
        return True
    else:
        print("❌ Неверно. Вспомни: индексация начинается с НУЛЯ!")
        print(f"   Подсказка: третий предмет имеет индекс 2.")
        return False


def door_2():
    """ЗАДАЧА 2: Срез списка"""
    print("\n🚪 ДВЕРЬ 2. СРЕЗЫ СПИСКА")
    print("Страж говорит: 'У меня есть последовательность чисел.'")
    
    numbers = [10, 20, 30, 40, 50, 60, 70]
    print("Числа:", numbers)
    print("\nЗагадка: 'Назови числа с индекса 2 по индекс 5 (не включая 5).'")
    
    answer = input("Какие это числа? (через пробел): ").strip()
    
    # Правильный ответ: 30 40 50 (срез [2:5])
    if answer == "30 40 50":
        print("✅ Верно! Дверь открывается.")
        return True
    else:
        print("❌ Неверно. Вспомни: срез [начало:конец] НЕ включает конец.")
        print(f"   Подсказка: numbers[2:5] = {numbers[2:5]}")
        return False


def door_3():
    """ЗАДАЧА 3: Отрицательные индексы"""
    print("\n🚪 ДВЕРЬ 3. ОТРИЦАТЕЛЬНЫЕ ИНДЕКСЫ")
    print("Страж говорит: 'Я загадал слово.'")
    
    word = "подземелье"
    print("Слово:", word)
    print("\nЗагадка: 'Какая буква стоит ПРЕДПОСЛЕДНЕЙ в этом слове?'")
    
    answer = input("Какая это буква? ").lower().strip()
    
    # Правильный ответ: ь (индекс -2)
    if answer == "ь":
        print("✅ Верно! Дверь открывается.")
        return True
    else:
        print("❌ Неверно. Вспомни: отрицательный индекс идёт с конца.")
        print(f"   Подсказка: word[-2] = '{word[-2]}'")
        return False


def door_4():
    """ЗАДАЧА 4: Переворот строки (срезы или reversed)"""
    print("\n🚪 ДВЕРЬ 4. ПЕРЕВОРОТ")
    print("Страж говорит: 'Я скажу слово задом наперёд.'")
    
    secret = "шалаш"
    print(f"Загадка: слово '{secret}' наоборот звучит так же?")
    
    reversed_secret = secret[::-1]
    print(f"Перевёрнутое слово: '{reversed_secret}'")
    
    answer = input("Это палиндром? (да/нет): ").lower().strip()
    
    # Правильный ответ: да
    if answer == "да" and secret == reversed_secret:
        print("✅ Верно! Это палиндром. Дверь открывается.")
        return True
    else:
        print("❌ Неверно.")
        return False


def door_5():
    """ЗАДАЧА 5: Разбить и собрать обратно"""
    print("\n🚪 ДВЕРЬ 5. SPLIT И JOIN")
    print("Страж говорит: 'У меня есть фраза, но слова перепутаны.'")
    
    phrase = "Python from World Hello"
    print("Фраза:", phrase)
    print("\nЗагадка: 'Переверни порядок слов, чтобы получить правильную фразу.'")
    
    answer = input("Какая фраза должна получиться? ").strip()
    
    # Правильный ответ: Hello World from Python
    words = phrase.split()
    correct = " ".join(words[::-1])
    
    if answer.lower() == correct.lower():
        print("✅ Верно! Дверь открывается.")
        return True
    else:
        print("❌ Неверно.")
        print(f"   Подсказка: нужно перевернуть список слов.")
        print(f"   Правильный ответ: {correct}")
        return False


# ---------- ОСНОВНАЯ ПРОГРАММА ----------

def main():
    print("\n" + "="*50)
    print("🏰 ЗАГАДКИ ДРЕВНЕГО СТРАЖА")
    print("="*50)
    print("\nТы заходишь в тёмное подземелье.")
    print("Перед тобой 5 дверей, и у каждой стоит страж.")
    print("Чтобы пройти, нужно решить его загадку.")
    print("Если ошибёшься — потеряешь здоровье!")
    
    health = 100
    doors_opened = 0
    doors = [door_1, door_2, door_3, door_4, door_5]
    
    for i, door in enumerate(doors, 1):
        show_status(doors_opened)
        print(f"\nЗдоровье: {health}")
        
        if health <= 0:
            print("\n💀 Ты погиб. Подземелье поглотило тебя.")
            break
        
        # Пытаемся открыть дверь (даём 2 попытки)
        attempts = 2
        while attempts > 0:
            success = door()
            if success:
                doors_opened += 1
                break
            else:
                attempts -= 1
                if attempts > 0:
                    print(f"⚠️ Осталось попыток: {attempts}. Здоровье -20")
                    health -= 20
                else:
                    print("💥 Страж атакует! Ты теряешь 30 здоровья и идёшь дальше.")
                    health -= 30
    
    # Финальный результат
    print("\n" + "="*50)
    print("🏁 ИТОГ")
    print("="*50)
    print(f"Открыто дверей: {doors_opened} из 5")
    print(f"Осталось здоровья: {health}")
    
    if doors_opened == 5:
        print("\n🎉 ПОЗДРАВЛЯЮ! Ты прошёл все загадки стража!")
        print("Ты получаешь сундук с сокровищами!")
    elif doors_opened >= 3:
        print("\n👍 Неплохо! Ты открыл больше половины дверей.")
    else:
        print("\n📚 Стоит повторить тему списков и срезов.")


if __name__ == "__main__":
    main()
